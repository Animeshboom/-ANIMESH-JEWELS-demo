export const getAllProducts = (): Product[] => {
  return PRODUCTS_CATALOGUE
}

export const getProductById = (idOrSlug: string): Product | undefined => {
  return PRODUCTS_CATALOGUE.find(
    (p) => p.id === idOrSlug || p.slug === idOrSlug
  )
}

export const getRelatedProducts = (currentId: string, limit = 3): Product[] => {
  const current = getProductById(currentId)
  if (!current) {
    return PRODUCTS_CATALOGUE.slice(0, limit)
  }

  // Find products in same category or collection first
  const sameCategory = PRODUCTS_CATALOGUE.filter(
    (p) => p.id !== currentId && p.category === current.category
  )
  const sameCollection = PRODUCTS_CATALOGUE.filter(
    (p) =>
      p.id !== currentId &&
      p.collection === current.collection &&
      !sameCategory.includes(p)
  )
  const others = PRODUCTS_CATALOGUE.filter(
    (p) =>
      p.id !== currentId &&
      !sameCategory.includes(p) &&
      !sameCollection.includes(p)
  )

  return [...sameCategory, ...sameCollection, ...others].slice(0, limit)
}
